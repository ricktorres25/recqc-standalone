"""
_vendor_check.py - the start check for RecQC's vendored platform files.

RecQC code, not vendored (adapted from MAD/Intake Scanner/cores/_vendor_check.py).
Standard library only, and nothing runs at import, so a test can load this file by
path even when the vendored copies are damaged. It runs unchanged in CPython and in
Pyodide.

cores/__init__.py calls require_vendored() the first time anything imports the
package, so a file that differs from VENDORED.json stops RecQC before any vendored
code runs. In the browser that also catches a bad download or a stale cache.

py/vendor_cores.sh also runs this file as a script:
    python3 _vendor_check.py write <cores dir>     rows on stdin -> VENDORED.json
    python3 _vendor_check.py check <cores dir>     exit 0 if every file matches, else 1
    python3 _vendor_check.py lift <out file> <source folder> <source path> <names> [<imports>]
                                                   source on stdin -> the named
                                                   top-level functions and constants,
                                                   verbatim
    python3 _vendor_check.py lift-js <out file> <source folder> <source path> <names> <shared>
                                                   source on stdin -> the named
                                                   JavaScript declarations, verbatim
    python3 _vendor_check.py write-js <app dir>    rows on stdin -> app/VENDORED.json
so the manifests are written and read in one place.
"""
import ast
import hashlib
import json
import re
import sys
from pathlib import Path

MANIFEST_NAME = "VENDORED.json"

# Manifest fields, in the order vendor_cores.sh passes them on each stdin row.
# Lift rows carry a sixth field, the lifted function and constant names (comma-separated),
# and may carry a seventh, the import lines those functions need (semicolon-separated).
# JavaScript lift rows carry the declaration names and the shared page variables.
ROW_FIELDS = ("path", "source_folder", "source_path", "repo", "commit")

MANIFEST_NOTE = ("Written by py/vendor_cores.sh. Do not edit by hand. RecQC refuses to start "
                 "if a file below differs from its sha256, and tests/test_vendored.py checks "
                 "each file against its source repo at the recorded commit. An entry with "
                 "'symbols' holds only those functions and constants, lifted verbatim from source_path, "
                 "plus the source's own import lines listed under 'imports', if any.")

JS_MANIFEST_NOTE = ("Written by py/vendor_cores.sh. Do not edit by hand. Each file below holds "
                    "the declarations named in 'symbols', lifted verbatim from source_path at "
                    "the recorded commit, then a generated footer that declares the page "
                    "variables named in 'shared' and exports the declarations. "
                    "tests/test_vendored.py checks each file against its source repo. The "
                    "browser does not check these files at start.")

# Header of a lifted file. No commit and no date in it, so a refresh with unchanged
# source functions leaves the file byte-identical (the commit is in VENDORED.json).
LIFT_HEADER = (
    "# {name} - GENERATED by py/vendor_cores.sh. Do not edit.\n"
    "#\n"
    "# The functions below are lifted verbatim from MAD/{source_folder}/{source_path}\n"
    "# (the commit is in VENDORED.json). That file cannot be vendored whole: it imports\n"
    "# the platform's web app and database layers. These functions use builtins only.\n"
)

# The header of a lift whose functions need some of their file's imports. Only the last
# sentence differs; the import lines follow it, copied verbatim (see lift_imports).
LIFT_HEADER_IMPORTS = (
    "# {name} - GENERATED by py/vendor_cores.sh. Do not edit.\n"
    "#\n"
    "# The functions below are lifted verbatim from MAD/{source_folder}/{source_path}\n"
    "# (the commit is in VENDORED.json). That file cannot be vendored whole: it imports\n"
    "# the platform's web app and database layers. These functions need only the imports\n"
    "# below, copied verbatim from the same file.\n"
)

JS_LIFT_HEADER = (
    "// {name} - GENERATED by py/vendor_cores.sh. Do not edit.\n"
    "//\n"
    "// The declarations below are lifted verbatim from MAD/{source_folder}/{source_path}\n"
    "// (the commit is in app/VENDORED.json). That page cannot be used whole: it is the\n"
    "// platform's full web app. Only the footer at the end is RecQC's, and it is generated.\n"
)

# A top-level JavaScript declaration of `name`: it starts the line, at column 0.
JS_DECLARATION = r"(?:async\s+function|function|class|const|let|var)\s+{name}\b"


class VendoredCoreError(RuntimeError):
    """A vendored file is missing, or its bytes differ from VENDORED.json."""


def sha256_file(path):
    """sha256 of a file's bytes, as lowercase hex."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def load_manifest(cores_dir):
    """Read VENDORED.json from cores_dir. Raises OSError or ValueError if it cannot."""
    return json.loads((Path(cores_dir) / MANIFEST_NAME).read_text(encoding="utf-8"))


def check_vendored(cores_dir):
    """Compare every file listed in VENDORED.json with its recorded sha256.

    Returns a list of problems, one line each. An empty list means every listed
    file is present and byte-identical to what vendor_cores.sh wrote.
    """
    cores_dir = Path(cores_dir)
    try:
        entries = load_manifest(cores_dir)["files"]
    except (OSError, ValueError, KeyError, TypeError) as e:
        return [f"cores/{MANIFEST_NAME} is missing or unreadable ({e})"]
    if not isinstance(entries, list) or not entries:
        return [f"cores/{MANIFEST_NAME} lists no files"]

    problems = []
    for entry in entries:
        if not isinstance(entry, dict):
            problems.append(f"cores/{MANIFEST_NAME} has a malformed entry")
            continue
        rel = str(entry.get("path", "?"))
        path = cores_dir / rel
        if not path.is_file():
            problems.append(f"cores/{rel} is missing")
            continue
        recorded = str(entry.get("sha256", ""))
        found = sha256_file(path)
        if found != recorded:
            problems.append(f"cores/{rel} differs from {MANIFEST_NAME} "
                            f"(sha256 recorded {recorded[:12]}, found {found[:12]})")
    return problems


def require_vendored(cores_dir):
    """Raise VendoredCoreError, naming every bad file, if check_vendored finds any."""
    problems = check_vendored(cores_dir)
    if problems:
        raise VendoredCoreError(
            "The vendored cores failed their start check, so RecQC will not run.\n  "
            + "\n  ".join(problems)
            + "\nFiles under py/cores/ change only through py/vendor_cores.sh. "
              "Restore them with git, or run py/vendor_cores.sh again.")


def _constant_name(node):
    """The name a top-level `NAME = ...` or `NAME: type = ...` statement assigns, else None."""
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        return node.targets[0].id
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
        return node.target.id
    return None


def lift_functions(source, names):
    """Return the named top-level functions and constants of `source`, verbatim, in the
    order named.

    Each function runs from its first line (its first decorator, if any) to its last
    line, and a constant (a top-level `NAME = ...`) over the lines of its statement, so
    the text is byte-identical to the source. A constant's trailing comment on its last
    line comes with it; comment lines above it do not. Raises ValueError if a name is
    missing or defined twice at top level.
    """
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    found = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            name, start = node.name, min([node.lineno] + [d.lineno for d in node.decorator_list])
        else:
            name, start = _constant_name(node), node.lineno
        if name not in names:
            continue
        if name in found:
            raise ValueError(f"{name} is defined twice at top level")
        found[name] = "".join(lines[start - 1:node.end_lineno])
    missing = [n for n in names if n not in found]
    if missing:
        raise ValueError("not found as top-level functions or constants: " + ", ".join(missing))
    return [found[n] for n in names]


def lift_imports(source, wanted):
    """Return the named import lines of `source`, in the order named.

    Each one must be a whole line of the source holding exactly one top-level import
    statement, so a lifted function gets the very imports its own file gives it.
    Raises ValueError naming any line that is not.
    """
    lines = source.splitlines()
    present = {lines[node.lineno - 1] for node in ast.parse(source).body
               if isinstance(node, (ast.Import, ast.ImportFrom)) and node.lineno == node.end_lineno}
    missing = [w for w in wanted if w not in present]
    if missing:
        raise ValueError("not found as one-line top-level imports: " + "; ".join(missing))
    return list(wanted)


def render_lift(name, source_folder, source_path, source, names, imports=()):
    """The full text of a lifted file: the header, the import lines if any, then each
    function or constant, two blank lines apart."""
    template = LIFT_HEADER_IMPORTS if imports else LIFT_HEADER
    header = template.format(name=name, source_folder=source_folder, source_path=source_path)
    # A lift that holds constants says so; a functions-only lift keeps its header as it was.
    constants = [n for n in names if not any(
        isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == n
        for node in ast.parse(source).body)]
    if constants:
        header = header.replace("# The functions below are", "# The functions and constants below are", 1)
    if imports:
        header += "\n" + "".join(line + "\n" for line in lift_imports(source, imports))
    bodies = [f if f.endswith("\n") else f + "\n" for f in lift_functions(source, names)]
    return header + "\n\n" + "\n\n".join(bodies)


def lift_js(source, names):
    """Return the named top-level JavaScript declarations of `source`, verbatim, in the
    order named.

    The standard library has no JavaScript parser, so this goes by the source's layout
    and refuses (ValueError) whenever the layout does not fit. A declaration starts on
    the one line that begins with it. It ends at the first later line that starts with
    '}', or, when its first line opens a template string (ends with a backtick), at the
    first later line that is exactly '`;', and that string must hold no backtick and no
    '${'. Every line in between must be blank or indented, so a missed end cannot
    swallow the next declaration. vendor_cores.sh also runs node --check on the result.
    """
    lines = source.splitlines(keepends=True)
    found = []
    for name in names:
        start_re = re.compile(JS_DECLARATION.format(name=re.escape(name)))
        starts = [i for i, line in enumerate(lines) if start_re.match(line)]
        if len(starts) != 1:
            raise ValueError(f"{name}: {len(starts)} top-level declarations found, expected 1")
        start = starts[0]
        template = lines[start].rstrip("\n").endswith("`")
        for end in range(start + 1, len(lines)):
            line = lines[end]
            if (line.rstrip("\n") == "`;") if template else line.startswith("}"):
                break
            if template and ("`" in line or "${" in line):
                raise ValueError(f"{name}: its template string holds a backtick or ${{, "
                                 f"line {end + 1}")
            if not template and line.strip() and not line[0].isspace():
                raise ValueError(f"{name}: an unindented line before its end, line {end + 1}")
        else:
            raise ValueError(f"{name}: no end found after line {start + 1}")
        found.append("".join(lines[start:end + 1]))
    return found


def render_js_lift(name, source_folder, source_path, source, names, shared):
    """The full text of a lifted JavaScript module: the header, each declaration a blank
    line apart, then the footer. The footer declares the page variables in `shared` (the
    platform's page declares them at top level, and the lifted declarations read and set
    them), exports a `shared` object to read and set them through, and exports the
    declarations."""
    header = JS_LIFT_HEADER.format(name=name, source_folder=source_folder, source_path=source_path)
    bodies = [d if d.endswith("\n") else d + "\n" for d in lift_js(source, names)]
    footer = ["// RecQC footer (generated): the page variables the declarations above share."]
    footer += [f"let {v} = null;" for v in shared]
    footer.append("export const shared = {")
    for v in shared:
        footer.append(f"  get {v}() {{ return {v}; }},")
        footer.append(f"  set {v}(value) {{ {v} = value; }},")
    footer.append("};")
    footer.append("export { " + ", ".join(names) + " };")
    return header + "\n" + "\n".join(bodies) + "\n" + "\n".join(footer) + "\n"


def write_manifest(cores_dir, rows):
    """Write VENDORED.json from vendor_cores.sh's rows (one 'a|b|c|d|e[|f[|g]]' line per file).

    The sha256 is taken here, from the file as it now sits under cores/.
    No timestamp is written, so a refresh with unchanged sources leaves the
    manifest byte-identical.
    """
    cores_dir = Path(cores_dir)
    files = []
    for line in rows:
        if not line.strip():
            continue
        values = line.rstrip("\n").split("|")
        if len(values) not in (len(ROW_FIELDS), len(ROW_FIELDS) + 1, len(ROW_FIELDS) + 2):
            raise ValueError(f"bad manifest row from vendor_cores.sh: {line!r}")
        entry = dict(zip(ROW_FIELDS, values))
        if len(values) > len(ROW_FIELDS):
            entry["symbols"] = values[len(ROW_FIELDS)].split(",")
        if len(values) > len(ROW_FIELDS) + 1:
            entry["imports"] = values[len(ROW_FIELDS) + 1].split(";")
        entry["sha256"] = sha256_file(cores_dir / entry["path"])
        files.append(entry)
    doc = {"written_by": "py/vendor_cores.sh", "note": MANIFEST_NOTE, "files": files}
    (cores_dir / MANIFEST_NAME).write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")


def write_js_manifest(app_dir, rows):
    """Write app/VENDORED.json from vendor_cores.sh's JavaScript rows
    (one 'path|folder|source path|repo|commit|names|shared' line per file)."""
    app_dir = Path(app_dir)
    files = []
    for line in rows:
        if not line.strip():
            continue
        values = line.rstrip("\n").split("|")
        if len(values) != len(ROW_FIELDS) + 2:
            raise ValueError(f"bad JavaScript manifest row from vendor_cores.sh: {line!r}")
        entry = dict(zip(ROW_FIELDS, values))
        entry["symbols"] = values[len(ROW_FIELDS)].split(",")
        entry["shared"] = values[len(ROW_FIELDS) + 1].split(",")
        entry["sha256"] = sha256_file(app_dir / entry["path"])
        files.append(entry)
    doc = {"written_by": "py/vendor_cores.sh", "note": JS_MANIFEST_NOTE, "files": files}
    (app_dir / MANIFEST_NAME).write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "write" and len(sys.argv) == 3:
        write_manifest(sys.argv[2], sys.stdin.read().splitlines())
        sys.exit(0)
    if cmd == "check" and len(sys.argv) == 3:
        found_problems = check_vendored(sys.argv[2])
        for p in found_problems:
            print(p, file=sys.stderr)
        sys.exit(1 if found_problems else 0)
    if cmd == "lift" and len(sys.argv) in (6, 7):
        out = Path(sys.argv[2])
        imports = sys.argv[6].split(";") if len(sys.argv) == 7 else ()
        text = render_lift(out.name, sys.argv[3], sys.argv[4], sys.stdin.read(),
                           sys.argv[5].split(","), imports)
        out.write_text(text, encoding="utf-8")
        sys.exit(0)
    if cmd == "lift-js" and len(sys.argv) == 7:
        out = Path(sys.argv[2])
        text = render_js_lift(out.name, sys.argv[3], sys.argv[4], sys.stdin.read(),
                              sys.argv[5].split(","), sys.argv[6].split(","))
        out.write_text(text, encoding="utf-8")
        sys.exit(0)
    if cmd == "write-js" and len(sys.argv) == 3:
        write_js_manifest(sys.argv[2], sys.stdin.read().splitlines())
        sys.exit(0)
    print("usage: _vendor_check.py write|check <cores dir>\n"
          "       _vendor_check.py lift <out file> <source folder> <source path> <names> [<imports>]\n"
          "       _vendor_check.py lift-js <out file> <source folder> <source path> <names> <shared>\n"
          "       _vendor_check.py write-js <app dir>",
          file=sys.stderr)
    sys.exit(2)
