#!/usr/bin/env python3
# build_precache.py - write sw.js's list of the files the offline copy keeps (M5).
#
# The list is every tracked file the page loads: index.html, the manifest and the
# icons, app/'s modules, the runner and py/cores/ (the files recqc_boot.mjs copies into Pyodide,
# with the configs beside them), every file under pyodide/, and the fonts. Each entry
# carries the file's sha256, which the service worker checks before caching it, and
# VERSION is a hash of the whole list, so a change to any file names a new cache.
#
# The files are git's: tracked, plus new ones not yet added (and not ignored), so a list
# built before a commit already names the files the commit adds. The hashes are of the
# files as they are on disk. CI checks the list on the pushed tree, so a listed file that
# was never committed, or one changed after the list was built, fails there.
#
# Run after changing any listed file, before committing:
#        python3 py/build_precache.py           rewrite the list in sw.js
#        python3 py/build_precache.py --check   change nothing; exit 1 if the list is stale
# Exit:  0 written or current, 1 stale (--check), 2 not run (git or sw.js missing)
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SW = REPO / "sw.js"
BEGIN = "// ---- generated by py/build_precache.py: do not edit by hand ----\n"
END = "// ---- end generated ----\n"

ROOT_FILES = ("index.html", "manifest.webmanifest")


def listed(path):
    """Whether a tracked file is one the page loads."""
    if path in ROOT_FILES or path == "py/recqc_runner.py":
        return True
    if path.startswith(("py/cores/", "pyodide/")):
        return True
    return (path.startswith("app/") and path.endswith(".mjs")) or \
           (path.startswith("icons/") and path.endswith(".png")) or \
           (path.startswith("fonts/") and path.endswith(".woff2"))


def tracked_files(repo=REPO):
    out = subprocess.run(["git", "-C", str(repo), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                         check=True, capture_output=True).stdout.decode("utf-8")
    return sorted(p for p in out.split("\0") if p and listed(p))


def precache(repo=REPO, paths=None):
    """[(path, sha256)] for the listed files, read from disk."""
    paths = tracked_files(repo) if paths is None else paths
    return [(p, hashlib.sha256((repo / p).read_bytes()).hexdigest()) for p in paths]


def version(entries):
    """The list's hash: the service worker's cache is named recqc-<version>."""
    return hashlib.sha256("".join(f"{p} {s}\n" for p, s in entries).encode()).hexdigest()[:16]


def generated_block(entries):
    rows = ",\n".join(f"  [{json.dumps(p)}, {json.dumps(s)}]" for p, s in entries)
    return f'{BEGIN}const VERSION = "{version(entries)}";\nconst PRECACHE = [\n{rows},\n];\n{END}'


def with_block(sw_text, block):
    """sw.js's text with its generated block replaced."""
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if len(pattern.findall(sw_text)) != 1:
        raise ValueError("sw.js must hold exactly one generated block")
    return pattern.sub(lambda _: block, sw_text)


def main():
    ap = argparse.ArgumentParser(description="Write the offline copy's file list into sw.js")
    ap.add_argument("--check", action="store_true", help="exit 1 if the list in sw.js is stale")
    args = ap.parse_args()
    if not SW.is_file():
        print(f"NOT RUN  {SW} not found")
        return 2
    try:
        entries = precache()
    except (OSError, subprocess.CalledProcessError) as e:
        print(f"NOT RUN  could not list the tracked files: {e}")
        return 2
    current = SW.read_text(encoding="utf-8")
    wanted = with_block(current, generated_block(entries))
    if args.check:
        if wanted != current:
            print("STALE    sw.js's precache list does not match the files; run python3 py/build_precache.py")
            return 1
        print(f"CURRENT  sw.js lists {len(entries)} files")
        return 0
    if wanted != current:
        SW.write_text(wanted, encoding="utf-8")
    size = sum((REPO / p).stat().st_size for p, _ in entries)
    print(f"wrote    sw.js: {len(entries)} files, {size / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
